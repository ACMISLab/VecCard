def read_csv(workload_type='short', num=100):
    file_path = data_path("predicate", "business_table_" + workload_type + "_predicates.csv")
    if not file_path.exists():
        return pd.DataFrame(columns=["expression", "feature"])
    data = pd.read_csv(file_path)
    data = data.head(num)
    return data


def load_workload(workload_type, workload_num, workload_table, workload_dim):
    workloads = []
    df = read_csv(workload_type, workload_num)
    if df.empty:
        return workloads
    expression = df["expression"]
    feature = df["feature"]
    length = len(expression)
    for i in range(length):
        table, expr = expression[i].split('.', 1)
        vector = np.array(eval(feature[i]))
        if vector.size > workload_dim:
            vector = vector[:workload_dim]
        elif vector.size < workload_dim:
            random_vector = np.random.uniform(-1, 1, size=workload_dim - vector.size)
            random_vector = np.round(random_vector, 16)
            vector = np.append(np.array(vector), random_vector)

        #sql = f"select  /*+ vector_pre */ name, city, stars,feature_index$distance from vector({workload_table},feature,array{str(vector.tolist())},10) limit 4;"

        #------------------------------
        sql = "select feature<*>array" + str(vector.tolist()) + " as distance, name, city, stars\n"
        # sql = "select count(*)\n"
        sql += "from " + workload_table + "\n"
        # sql += "where " + expr + ";"
        sql += "where " + expr + "\n"
        # sql += "order by distance\n"
        sql += "limit 4;"
        workloads.append(sql)
    return workloads


async def parallel_execute_query(query, dingodb, timeout):
    start_time = time.time()
    status = None
    elapsed_time = None
    try:
        result = await asyncio.wait_for(dingodb.execute_pool(query), timeout)
    except asyncio.TimeoutError:
        status = 1
        elapsed_time = timeout
        print("timeout")
    except Exception as e:
        status = 2
        elapsed_time = time.time() - start_time
        print(f"发生错误: {e}")
    else:
        status = 0
        elapsed_time = time.time() - start_time
        print(f"查询执行时间：{elapsed_time:.4f} seconds")
    finally:
        return status, elapsed_time, start_time


def calculate_metrics(results, task_start_time, timeout):
    if not results:
        return
    results_normal = [(status, elapsed_time, waiting_time) for status, elapsed_time, waiting_time in results if
                      status == 0]

    results_timeout = [(status, elapsed_time, waiting_time) for status, elapsed_time, waiting_time in results if
                       status == 1]
    results_error = [(status, elapsed_time, waiting_time) for status, elapsed_time, waiting_time in results if
                     status == 2]

    # 计算成功率并输出
    success_rate = (len(results_normal) + len(results_error)) / len(results)
    print(f"成功率：{success_rate:.4f}")

    # 计算超时率并输出
    failure_rate = 1 - success_rate
    print(f"超时率：{failure_rate:.4f}")
    # 将异常查询的执行时间设置为最大执行时间
    adjusted_results = results_normal

    elapsed_times = [elapsed_time for _, elapsed_time, _ in results_normal]
    if not elapsed_times:
        return
    average_elapsed_time = sum(elapsed_times) / len(elapsed_times)

    '''
    for status, elapsed_time, start_time in results_timeout:
        adjusted_results.append((status, timeout, start_time))
    '''

    for status, elapsed_time, start_time in results_error:
        adjusted_results.append((status, average_elapsed_time, start_time))

    total_queries = len(adjusted_results)

    print('total_queries:', total_queries)

    # 计算总的查询数、总的执行时间和总的等待时间
    total_time = sum(
        elapsed_time for _, elapsed_time, _ in adjusted_results if elapsed_time is not None)

    # 计算平均查询延迟
    average_latency = total_time / total_queries
    print(f"平均查询延迟：{average_latency:.4f} seconds")

    # 计算QPS
    qps = total_queries / total_time
    print(f"QPS：{qps:.4f} job/second")

    total_waiting_time = sum(
        (start_time - task_start_time)
        for i, (_, _, start_time) in enumerate(adjusted_results))
    # 计算平均等待时间
    average_waiting_time = total_waiting_time / len(adjusted_results)
    print(f"平均等待时间：{average_waiting_time:.4f} seconds")


async def parallel(config, args):
    db_config = config["database"]
    select_config = config["select"]
    timeout = select_config["timeout"]
    ssh_config = config["ssh"]

    print(select_config)
    # get database
    dingodb = dg.DingoDB(db_config["host"], db_config["port"], db_config["user"], db_config["password"],
                         db_config["db"])
    await dingodb.create_pool()

    workloads = load_workload(select_config["workload_type"], select_config["workload_num"],
                              config["database"]["table"], config["create"]["dimension"])
    if not workloads:
        return
    # workloads = workloads[44:]

    print('start execute job, concurrency:', select_config["concurrency"], 'total:', len(workloads), 'workloads',
          "start time:", time.strftime("%Y-%m-%d %H:%M:%S", time.localtime()))

    start_time = int(server.get_server_time(ssh_config["host"], ssh_config["port"], ssh_config["user"],
                                            ssh_config["password"]))
    print("sever start time:", start_time)

    # 创建一个任务列表
    tasks = [parallel_execute_query(workload, dingodb, timeout) for workload in workloads]

    # 控制并发度
    semaphore = asyncio.Semaphore(select_config["concurrency"])

    async def run_task(task):
        async with semaphore:
            return await task

    task_start_time = time.time()

    # 并发执行任务，同时控制并发度
    results = await asyncio.gather(*(run_task(task) for task in tasks))

    # 计算相关指标
    calculate_metrics(results, task_start_time, timeout)
    await dingodb.close_pool()

    end_time = int(server.get_server_time(ssh_config["host"], ssh_config["port"], ssh_config["user"],
                                          ssh_config["password"]))
    print("sever end time:", end_time)
    if config["prometheus"]["enable"]:
        prometheus.get_metrics(start_time - 25, end_time + 25, config)
    # print()
    # server.restart_server(config, args)


def select_workload(config, args):
    asyncio.run(parallel(config, args))


